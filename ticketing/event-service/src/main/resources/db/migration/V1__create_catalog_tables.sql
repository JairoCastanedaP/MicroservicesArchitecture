-- Sesión 2: esquema inicial del catálogo (event_db)
-- Flyway ejecuta este script una sola vez y lo registra en la tabla flyway_schema_history.
-- Regla de oro: un script ya aplicado NO se modifica; los cambios van en un V2__..., V3__...

CREATE TABLE venues (
                        id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name     VARCHAR(120) NOT NULL,
                        city     VARCHAR(80)  NOT NULL,
                        address  VARCHAR(200),
                        capacity INTEGER      NOT NULL CHECK (capacity > 0)
);

CREATE TABLE events (
                        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name        VARCHAR(150)  NOT NULL,
                        description VARCHAR(1000),
                        category    VARCHAR(20)   NOT NULL,
                        status      VARCHAR(20)   NOT NULL,
                        date_time   TIMESTAMP     NOT NULL,
                        venue_id    BIGINT        NOT NULL REFERENCES venues (id)
);

CREATE INDEX idx_events_venue_id ON events (venue_id);
CREATE INDEX idx_events_date_time ON events (date_time);

CREATE TABLE ticket_categories (
                                   id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   name     VARCHAR(80)    NOT NULL,
                                   price    NUMERIC(10, 2) NOT NULL CHECK (price > 0),
                                   capacity INTEGER        NOT NULL CHECK (capacity > 0),
                                   event_id BIGINT         NOT NULL REFERENCES events (id) ON DELETE CASCADE
);

CREATE INDEX idx_ticket_categories_event_id ON ticket_categories (event_id);
