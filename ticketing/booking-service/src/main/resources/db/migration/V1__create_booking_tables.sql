-- Sesión 2: esquema inicial de reservas (booking_db)
-- event_id y ticket_category_id NO son claves foráneas: esos datos viven en otra base de datos
-- (event_db, dueña event-service). Son referencias lógicas que se validarán por API en la Sesión 3.

CREATE TABLE bookings (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id           BIGINT         NOT NULL,
    ticket_category_id BIGINT         NOT NULL,
    customer_email     VARCHAR(150)   NOT NULL,
    quantity           INTEGER        NOT NULL CHECK (quantity > 0),
    unit_price         NUMERIC(10, 2) NOT NULL CHECK (unit_price > 0),
    total_amount       NUMERIC(12, 2) NOT NULL,
    status             VARCHAR(20)    NOT NULL,
    created_at         TIMESTAMP      NOT NULL,
    expires_at         TIMESTAMP      NOT NULL,
    confirmed_at       TIMESTAMP,
    -- Bloqueo optimista: JPA incrementa esta columna en cada UPDATE
    version            BIGINT         NOT NULL DEFAULT 0
);

CREATE INDEX idx_bookings_customer_email ON bookings (customer_email);
CREATE INDEX idx_bookings_event_category ON bookings (event_id, ticket_category_id);

CREATE TABLE tickets (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(36) NOT NULL UNIQUE,
    issued_at  TIMESTAMP   NOT NULL,
    booking_id BIGINT      NOT NULL REFERENCES bookings (id)
);

CREATE INDEX idx_tickets_booking_id ON tickets (booking_id);
